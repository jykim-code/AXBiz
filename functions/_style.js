// 데이터 문체 기준 정규화 — CLAUDE.md 「데이터 문체 기준」 중 기계적으로 판정되는 항목만 처리한다.
// 저장 경로가 둘(발행 _publish.js · 자동화 진입점 api/reports.js)이라 규칙을 한 곳에 둔다.

// 온점 금지: 명사형으로 끝나는 항목에 붙은 끝 온점을 제거한다("상품화." → "상품화").
// 서술형(…다.)은 문장을 명사형으로 다시 쓰는 작업이라 자동으로 건드리지 않고 그대로 둔다.
// 끝 온점만 보므로 문장 중간의 버전 표기("Apache 2.0")는 영향받지 않는다.
export function stripTrailingPeriod(s) {
  const t = String(s == null ? '' : s);
  return /다\.$/.test(t) ? t : t.replace(/\.+$/, '');
}

// 「축」 금지: 「경쟁 축」류 표현을 구체적인 말로 바꾼다(CLAUDE.md 2026-08-13 지시).
// 프롬프트에 금지 지시를 넣어도 계속 나온다(실측: 주간 인사이트 LLM 초안 3건 중 3건에 「경쟁 축」).
// 좌표축·회전축 같은 정상 용례를 건드리지 않도록 지침에 적힌 조합만 치환한다.
// 「지점」·「기준」은 「축」과 같이 받침이 있어 뒤따르는 조사가 그대로 맞지만,
// 「요소」는 받침이 없어 조사까지 바꿔야 한다(「차별화 축을」 → 「차별화 요소를」).
// 조사 규칙은 긴 것부터 둔다(「축이」가 「축이나」보다 먼저 걸리면 「요소가나」가 된다).
const AXIS_PAIRS = [
  [/차별화\s*축이나/g, '차별화 요소나'],
  [/차별화\s*축으로/g, '차별화 요소로'],
  [/차별화\s*축을/g, '차별화 요소를'],
  [/차별화\s*축은/g, '차별화 요소는'],
  [/차별화\s*축이/g, '차별화 요소가'],
  [/차별화\s*축과/g, '차별화 요소와'],
  [/차별화\s*축/g, '차별화 요소'],
  [/경쟁\s*축/g, '경쟁 지점'],
  [/대응\s*축/g, '대응 지점'],
  [/비교\s*축/g, '비교 기준'],
];
export function replaceAxisWord(s) {
  let t = String(s == null ? '' : s);
  for (const [re, to] of AXIS_PAIRS) t = t.replace(re, to);
  return t;
}

// 치환 목록에 없는 「축」 조합이 남았는지 본다. 목록을 늘려도 모델이 새 조합을 만들어 낸다
// (실측: 「경쟁 축」을 막으면 「평가 축」이 나왔다). 무엇으로 바꿀지는 문맥마다 달라
// 기계적으로 정할 수 없으므로, 탐지해서 재생성하거나 사람에게 넘긴다.
//  - 공백 뒤에 홀로 쓰인 「축」을 금지 용례로 본다(「평가 축이」)
//  - 붙여 쓴 복합어(좌표축·회전축·x축)는 정상 용례이므로 건드리지 않는다
//  - 뒤따르는 조사를 긍정 목록으로 본다. 「축」 다음에 오는 한글을 부정 lookahead 로 막으면
//    조사(축「이」)까지 걸러져 아무것도 탐지되지 않는다. 반대로 조사 목록에 없는 글자가
//    오면 「축소·축적·축약」 같은 별개 단어이므로 넘긴다.
const AXIS_ALONE = /\s축(?=[을은이가과으만도의에서나보부까마]|\s|$|[,.)\]])/;
export function hasAxisWord(s) {
  const t = String(s == null ? '' : s);
  return AXIS_ALONE.test(t) || /(?:경쟁|대응|차별화|비교)축/.test(t);
}

// em dash 금지: 연결에 쓰인 em dash 를 쉼표로 바꾼다("전략 수립—차량 데이터로" → "전략 수립, 차량 데이터로").
// 생성 요약(_summary.js)이 프롬프트의 금지 지시를 무시하고 넣는 경우가 있어 기계적으로 정규화한다.
// en dash(–)는 연도 범위("2025–2026")에 쓰일 수 있어 건드리지 않는다.
export function replaceEmDash(s) {
  return String(s == null ? '' : s)
    .replace(/\s*—\s*/g, ', ')
    .replace(/,\s*(?=,)/g, '') // "A, , B" 처럼 쉼표가 겹친 경우 정리
    .replace(/^[\s,]+/, '')
    .replace(/[\s,]+$/, '');
}
